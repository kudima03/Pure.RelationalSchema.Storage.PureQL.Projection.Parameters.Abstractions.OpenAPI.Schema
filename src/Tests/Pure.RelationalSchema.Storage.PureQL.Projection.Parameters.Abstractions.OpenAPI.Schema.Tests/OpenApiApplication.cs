using System.Text.Json.Nodes;
using Microsoft.AspNetCore.Builder;
using Microsoft.AspNetCore.Http;
using Microsoft.AspNetCore.Mvc;
using Microsoft.AspNetCore.TestHost;
using Microsoft.Extensions.DependencyInjection;
using Pure.RelationalSchema.Storage.PureQL.Projection.Parameters.Abstractions.ListParameter;
using Pure.RelationalSchema.Storage.PureQL.Projection.Parameters.Abstractions.Parameter;

namespace Pure.RelationalSchema.Storage.PureQL.Projection.Parameters.Abstractions.OpenAPI.Schema.Tests;

/// <summary>
/// An in-memory ASP.NET Core application with one endpoint that reads parameters and
/// writes a list parameter, whose OpenAPI document is generated by
/// <c>Microsoft.AspNetCore.OpenApi</c>, with or without the transformer.
/// </summary>
internal sealed record OpenApiApplication
{
    private readonly bool _transformed;

    public OpenApiApplication(bool transformed)
    {
        _transformed = transformed;
    }

    public async Task<JsonObject> DocumentAsync()
    {
        WebApplicationBuilder builder = WebApplication.CreateBuilder();
        _ = builder.WebHost.UseTestServer();
        _ = builder.Services.AddOpenApi(options =>
        {
            if (_transformed)
            {
                _ = options.AddDocumentTransformer<PureQLParametersDocumentTransformer>();
            }
        });

        await using WebApplication application = builder.Build();
        _ = application.MapOpenApi();
        _ = application
            .MapPost("/parameters", ([FromBody] IParameter[] parameters) => Results.Ok())
            .Produces<IListParameter>();

        await application.StartAsync();

        using HttpClient client = application.GetTestClient();
        string json = await client.GetStringAsync("/openapi/v1.json");

        await application.StopAsync();

        return JsonNode.Parse(json)!.AsObject();
    }
}
